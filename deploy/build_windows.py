            "--specpath",
            str(work / "spec"),
            "--paths",
            str(ROOT),
            "--hidden-import",
            "service.windows_service",
            "--hidden-import",
            "service.updater",
            "--hidden-import",
            "service.update_apply",
            "--hidden-import",
            "win32timezone",
            "--hidden-import",
            "servicemanager",
            "--collect-submodules",
            "win32",
            "--exclude-module",
            "fastapi",
            "--exclude-module",
            "uvicorn",
            "--exclude-module",
            "starlette",
            "--exclude-module",
