"""Reproducible Windows release build for ProShield.

    python -m deploy.build_windows --version 1.0.0 --channel testing

Produces **only** into the dedicated release directory::

    dist/windows/<version>/
        ProShield.exe                       native desktop shell (WebView2)
        ProShieldService.exe                Windows service host
        ProShieldSetup-v<version>.exe       installer
        manifest.json                       signed update metadata
        checksums.txt                       SHA-256 of every artefact
        build-report.json                   toolchain + hashes (reproducibility)

        _stage/                             the install payload the installer packs
        _pyinstaller/                       PyInstaller work directory

Nothing generated is ever written into ``app/``, ``scripts/``,
``frontend/src_upgraded_gemini/`` or any other source directory.  The single
source-tree side effect is the frontend build output, which Vite is already
configured to write to ``frontend/soc/`` (the location the backend serves).

What gets packaged (requirement 11) - an explicit allow-list, never a blanket
copy:

    runtime/       relocatable CPython + pinned site-packages
    app/           authoritative security implementation
    scripts/       proxy_server.py, ingress_server.py (entry points only)
    frontend/soc/  authoritative React UI (single-file bundle)
    service/       ProShieldService.exe
    desktop/       ProShield.exe + status.html
    deploy/        build_info.json, version.json, update public key

Excluded by construction: ``__pycache__``, ``*.pyc``, ``.pytest_cache``,
``logs/``, audit probes (``_audit_*``), demo/E2E helper scripts, debug dumps,
development secrets, and every legacy frontend file (``frontend/js``,
``frontend/css``, ``frontend/assets``, ``frontend/*.html``).
"""
