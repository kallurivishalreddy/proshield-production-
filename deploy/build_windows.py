def load_version_config() -> Dict[str, Any]:
    return json.loads(VERSION_FILE.read_text(encoding="utf-8"))


def tool_versions() -> Dict[str, str]:
    """Versions of every tool that shaped this build (reproducibility record).

    ``importlib.metadata.version`` takes the *distribution* name, which is not
    always the import name (``pywebview`` is imported as ``webview``), so the
    pairs are mapped explicitly.
    """
    import importlib.metadata as metadata

    versions: Dict[str, str] = {}
    for distribution, label in (
        ("pyinstaller", "pyinstaller"),
        ("cryptography", "cryptography"),
        ("pywin32", "pywin32"),
        ("pywebview", "pywebview"),
        ("pythonnet", "pythonnet"),
        ("pymongo", "pymongo"),
        ("fastapi", "fastapi"),
        ("uvicorn", "uvicorn"),
        ("pydantic", "pydantic"),
    ):
        try:
            versions[label] = metadata.version(distribution)
        except Exception:
            versions[label] = "unknown"
    versions["python"] = sys.version.split()[0]
    return versions


