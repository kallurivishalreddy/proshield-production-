def log(message: str) -> None:
    print(f"[build] {message}", flush=True)


def run(
    command: Sequence[str],
    cwd: Optional[Path] = None,
    check: bool = True,
    env: Optional[Dict[str, str]] = None,
) -> Tuple[int, str]:
    log("run: " + " ".join(str(part) for part in command))
    completed = subprocess.run(
        [str(part) for part in command],
        cwd=str(cwd or ROOT),
        capture_output=True,
        text=True,
        env=env,
        shell=False,
    )
    output = (completed.stdout or "") + (completed.stderr or "")
    if check and completed.returncode != 0:
        raise SystemExit(
            f"command failed ({completed.returncode}): {' '.join(command)}\n{output[-4000:]}"
        )
    return completed.returncode, output


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def git_value(args: Sequence[str], default: str = "unknown") -> str:
    try:
        code, output = run(["git", *args], check=False)
        if code == 0 and output.strip():
            return output.strip().splitlines()[0]
    except Exception:  # pragma: no cover
        pass
    return default


def rmtree(path: Path) -> None:
    if path.exists():
        shutil.rmtree(path, ignore_errors=True)


def copytree_filtered(
    source: Path,
    destination: Path,
    skip_names: Sequence[str] = ("__pycache__",),
) -> None:
    """Copy a tree while dropping caches and compiled artefacts."""

    def ignore(directory: str, names: List[str]) -> List[str]:
        dropped = []
        for name in names:
            if name in skip_names:
                dropped.append(name)
            elif name.endswith((".pyc", ".pyo", ".pyd.tmp")):
                dropped.append(name)
        return dropped

    shutil.copytree(source, destination, dirs_exist_ok=True, ignore=ignore)


#: Directories that must never appear in a packaged payload.
CACHE_DIR_NAMES = ("__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache", ".tox")
CACHE_FILE_SUFFIXES = (".pyc", ".pyo")


#: Frozen executables and the source trees they must be newer than.
FROZEN_SOURCE_PAIRS = (
    ("service/ProShieldService.exe", "service"),
    ("desktop/ProShield.exe", "desktop"),
)


def verify_frozen_freshness(stage: Path) -> Dict[str, Any]:
    """Refuse to package a frozen executable that is older than its own sources.

    ``--skip-service`` / ``--skip-desktop`` reuse previously frozen binaries for
    fast iteration.  That is only safe while those binaries really do contain the
    current sources - otherwise the release silently ships stale code.  This is
    not hypothetical: a build once replaced a freshly frozen (fixed) service with
    an older copy, and the packaged installer then carried the bug.

    Comparing modification times is a cheap, honest guard: if any file under
    ``service/`` (or ``desktop/``) is newer than the frozen image, the image
    cannot contain it.
    """
    checked: Dict[str, Any] = {}
    problems: List[str] = []

    for exe_rel, src_rel in FROZEN_SOURCE_PAIRS:
        exe = stage / exe_rel
        source_dir = ROOT / src_rel
        if not exe.is_file() or not source_dir.is_dir():
            continue

        exe_mtime = exe.stat().st_mtime
        newest_path = None
        newest_mtime = 0.0
        for candidate in source_dir.rglob("*.py"):
            stat = candidate.stat()
            if stat.st_mtime > newest_mtime:
                newest_mtime = stat.st_mtime
                newest_path = candidate

        checked[src_rel] = {
            "exe": exe_rel,
            "exe_mtime": exe_mtime,
            "newest_source": str(newest_path) if newest_path else None,
            "newest_source_mtime": newest_mtime,
            "fresh": newest_mtime <= exe_mtime + 1.0,
        }
        if newest_mtime > exe_mtime + 1.0:
            problems.append(
                f"{exe_rel} is OLDER than {src_rel}/ sources "
                f"(newest: {newest_path}) - re-freeze it by dropping "
                f"--skip-{src_rel}"
            )

    if problems:
        raise SystemExit(
            "frozen artefact freshness check FAILED:\n  - " + "\n  - ".join(problems)
        )
    return {"ok": True, "checked": checked}


def prune_stage(stage: Path) -> Dict[str, int]:
    """Remove caches and compiled artefacts from the staged payload.

    Required by requirement 11 (no ``__pycache__``, no pytest cache, no debug
    dumps).  ``shutil.copytree`` already skips these while copying, but the
    build *runs* the bundled interpreter to verify the runtime, and CPython
    writes ``__pycache__`` back into ``runtime/Lib`` when it does.  Pruning is
    therefore performed after all staging and freezing, immediately before the
    installer is compiled, so the payload is known-clean by construction.
    """
    removed_dirs = 0
    removed_files = 0

    for name in CACHE_DIR_NAMES:
        for path in list(stage.rglob(name)):
            if path.is_dir():
                shutil.rmtree(path, ignore_errors=True)
                removed_dirs += 1

    for suffix in CACHE_FILE_SUFFIXES:
        for path in list(stage.rglob(f"*{suffix}")):
            try:
                path.unlink()
                removed_files += 1
            except OSError:
                pass

    # Debug dumps and partially written downloads must never ship.
    for pattern in ("*.dmp", "*.dump", "*.part", "*.orig", "*.rej", "*.bak"):
        for path in list(stage.rglob(pattern)):
            try:
                path.unlink()
                removed_files += 1
            except OSError:
                pass

    return {"removed_dirs": removed_dirs, "removed_files": removed_files}


def audit_stage(stage: Path) -> Dict[str, Any]:
    """Fail the build if anything forbidden would be shipped (requirement 11).

    A build gate, not just a cleanup step: the release cannot be produced while
    the payload contains caches, compiled artefacts, debug dumps, development
    secrets, audit probes or legacy frontend assets.
    """
    problems: List[str] = []

    for name in CACHE_DIR_NAMES:
        found = list(stage.rglob(name))
        if found:
            problems.append(f"cache directory {name} ({len(found)} path(s))")

    for suffix in CACHE_FILE_SUFFIXES + (".part", ".dmp", ".dump"):
        found = list(stage.rglob(f"*{suffix}"))
        if found:
            problems.append(f"forbidden files *{suffix} ({len(found)} file(s))")

    # The update signing PRIVATE key must never be packaged; the public key may.
    for candidate in stage.rglob("*.pem"):
        if "private" in candidate.name.lower() or candidate.parent.name.lower() == "signing":
            problems.append(f"signing material packaged: {candidate.relative_to(stage)}")

    # Only the authoritative React bundle may ship; no legacy frontend assets.
    frontend = stage / "frontend"
    if frontend.is_dir():
        for entry in frontend.iterdir():
            if entry.is_dir() and entry.name != "soc":
                problems.append(f"legacy frontend directory: frontend/{entry.name}")
            elif entry.suffix.lower() in (".js", ".css", ".map"):
                problems.append(f"legacy frontend asset: frontend/{entry.name}")

    # Only the documented runtime entry points may ship from scripts/.
    scripts = stage / "scripts"
    if scripts.is_dir():
        allowed = set(RUNTIME_SCRIPTS)
        for entry in scripts.iterdir():
            if entry.is_file() and entry.name not in allowed:
                problems.append(f"development script packaged: scripts/{entry.name}")

    if problems:
        raise SystemExit(
            "payload audit FAILED (requirement 11):\n  - " + "\n  - ".join(problems)
        )
    return {"ok": True, "stage": str(stage)}


