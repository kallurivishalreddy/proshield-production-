def stage_frontend(skip: bool) -> Dict[str, Any]:
    """Build the authoritative React UI into frontend/soc/."""
    if skip:
        if not (FRONTEND_OUT / "index.html").is_file():
            raise SystemExit(
                "--skip-frontend requested but frontend/soc/index.html is missing"
            )
        log("frontend build skipped (using existing frontend/soc/index.html)")
    else:
        log("building the authoritative React UI (frontend/src_upgraded_gemini)")
        npm = shutil.which("npm") or shutil.which("npm.cmd")
        if npm is None:
            raise SystemExit("npm was not found on PATH; needed to build the UI")
        if not (FRONTEND_SRC / "node_modules").is_dir():
            run([npm, "install", "--no-audit", "--no-fund"], cwd=FRONTEND_SRC)
        run([npm, "run", "build"], cwd=FRONTEND_SRC)

    index = FRONTEND_OUT / "index.html"
    if not index.is_file():
        raise SystemExit(f"frontend build did not produce {index}")
    return {
        "ui_index": str(index),
        "ui_bytes": index.stat().st_size,
        "ui_sha256": sha256_file(index),
    }


def stage_runtime(stage: Path, skip: bool) -> Dict[str, Any]:
    """Create a relocatable Python runtime under ``stage/runtime``."""
    runtime = stage / "runtime"
    if skip:
        if not (runtime / "python.exe").is_file():
            raise SystemExit("--skip-runtime requested but no staged runtime exists")
        log("runtime staging skipped")
        return {"runtime": str(runtime), "skipped": True}

    rmtree(runtime)
    runtime.mkdir(parents=True, exist_ok=True)

    base_prefix = Path(sys.base_prefix)
    log(f"staging relocatable python from {base_prefix}")

    for directory in RUNTIME_PY_COPY_DIRS:
        source = base_prefix / directory
        if not source.is_dir():
            continue
        if directory == "Lib":
            runtime_lib = runtime / "Lib"
            runtime_lib.mkdir(parents=True, exist_ok=True)
            for entry in source.iterdir():
                if entry.name in LIB_EXCLUDES:
                    continue
                if entry.is_dir():
                    copytree_filtered(entry, runtime_lib / entry.name)
                elif not entry.name.endswith((".pyc", ".pyo")):
                    shutil.copy2(entry, runtime_lib / entry.name)
        else:
            copytree_filtered(source, runtime / directory)

    for filename in RUNTIME_PY_COPY_FILES:
        source = base_prefix / filename
        if source.is_file():
            shutil.copy2(source, runtime / filename)

    for dll in ("python3.dll",):
        source = base_prefix / dll
        if source.is_file():
            shutil.copy2(source, runtime / dll)
    for candidate in base_prefix.glob("python3*.dll"):
        shutil.copy2(candidate, runtime / candidate.name)

    site_packages = runtime / "Lib" / "site-packages"
    site_packages.mkdir(parents=True, exist_ok=True)

    log("installing pinned runtime dependencies into the bundled site-packages")
    run(
        [
            sys.executable,
            "-m",
            "pip",
            "install",
            "--no-warn-script-location",
            "--no-cache-dir",
            "--disable-pip-version-check",
            "--target",
            str(site_packages),
            "-r",
            str(DEPLOY_DIR / "requirements-runtime.txt"),
        ]
    )

    # A pyvenv.cfg copied from a venv would break relocatability.
    pyvenv = runtime / "pyvenv.cfg"
    if pyvenv.exists():
        pyvenv.unlink()

    # PYTHONDONTWRITEBYTECODE keeps these verification runs from writing
    # __pycache__ back into the runtime we just staged.
    verify_env = dict(os.environ)
    verify_env["PYTHONDONTWRITEBYTECODE"] = "1"

    python_exe = runtime / "python.exe"
    code, output = run([str(python_exe), "-c", "import sys; print(sys.version)"], env=verify_env)
    log(f"bundled runtime reports: {output.strip()}")
    code, output = run(
        [
            str(python_exe),
            "-c",
            "import fastapi, uvicorn, pymongo, pydantic; print('runtime deps ok')",
        ],
        env=verify_env,
    )
    log(output.strip())

    return {
        "runtime": str(runtime),
        "python": output.strip(),
        "runtime_deps_verified": "runtime deps ok" in output,
    }


def stage_sources(stage: Path, version_config: Dict[str, Any], build_info: Dict[str, Any]) -> Dict[str, Any]:
    """Copy the authoritative implementation into ``stage`` (allow-list only)."""
    log("staging the authoritative ProShield implementation")

    copytree_filtered(ROOT / "app", stage / "app")

    scripts_dst = stage / "scripts"
    scripts_dst.mkdir(parents=True, exist_ok=True)
    for name in RUNTIME_SCRIPTS:
        source = ROOT / "scripts" / name
        if not source.is_file():
            raise SystemExit(f"required runtime script is missing: {source}")
        shutil.copy2(source, scripts_dst / name)

    # Only the authoritative React UI is packaged - no legacy frontend files.
    ui_dst = stage / "frontend" / "soc"
    if ui_dst.exists():
        shutil.rmtree(ui_dst)
    copytree_filtered(FRONTEND_OUT, ui_dst)
    (stage / "frontend" / "login.html").write_text(LEGACY_REDIRECT_SHIM, encoding="utf-8")

    deploy_dst = stage / "deploy"
    deploy_dst.mkdir(parents=True, exist_ok=True)
    shutil.copy2(VERSION_FILE, deploy_dst / "version.json")
    if PUBLIC_KEY_FILE.is_file():
        shutil.copy2(PUBLIC_KEY_FILE, deploy_dst / PUBLIC_KEY_FILE.name)
        log(f"update public key staged ({PUBLIC_KEY_FILE.name})")
    else:
        log("WARNING: no update public key found - the update channel is fail-closed")
    (deploy_dst / "build_info.json").write_text(
        json.dumps(build_info, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    return {
        "app_files": sum(1 for _ in (stage / "app").rglob("*.py")),
        "packaged_scripts": list(RUNTIME_SCRIPTS),
        "ui_files": sorted(p.name for p in ui_dst.iterdir()),
    }


