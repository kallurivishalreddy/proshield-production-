def find_iscc() -> Optional[Path]:
    candidates = [
        Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Inno Setup 6" / "ISCC.exe",
        Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")) / "Inno Setup 6" / "ISCC.exe",
        Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "Inno Setup 6" / "ISCC.exe",
    ]
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    found = shutil.which("iscc")
    return Path(found) if found else None


def build_installer(
    release: Path,
    stage: Path,
    version: str,
    update_url: str,
    test_mode: bool,
) -> List[Dict[str, Any]]:
    iscc = find_iscc()
    if iscc is None:
        raise SystemExit(
            "Inno Setup 6 compiler (ISCC.exe) not found. Install it with:\n"
            "  winget install -e --id JRSoftware.InnoSetup"
        )

    outputs: List[Dict[str, Any]] = []
    variants = [("", False)]
    if test_mode:
        variants.append(("-testmode", True))

    # Inno requires a four-part numeric version resource.
    parts = [p for p in str(version).replace("-", ".").split(".") if p != ""]
    numeric = [int("".join(ch for ch in p if ch.isdigit()) or 0) for p in parts][:4]
    while len(numeric) < 4:
        numeric.append(0)
    version_info = ".".join(str(part) for part in numeric)

    for suffix, is_test in variants:
        base_name = f"ProShieldSetup-v{version}{suffix}"
        log(f"compiling installer {base_name}.exe (test_mode={is_test})")
        arguments = [
            str(iscc),
            f"/DAppVersion={version}",
            f"/DVersionInfoVersion={version_info}",
            f"/DStageRoot={stage}",
            f"/DOutputDir={release}",
            f"/DOutputBase={base_name}",
            f"/DUpdateUrl={update_url}",
            f"/DTestMode={'1' if is_test else '0'}",
            str(INNO_SCRIPT),
        ]
        code, output = run(arguments, check=False)
        tail = output.strip().splitlines()[-6:]
        if code != 0:
            raise SystemExit(
                f"ISCC failed ({code}) for {base_name}:\n" + "\n".join(tail)
            )
        exe = release / f"{base_name}.exe"
        if not exe.is_file():
            raise SystemExit(f"ISCC reported success but {exe} is missing")
        outputs.append(
            {
                "installer": str(exe),
                "installer_name": exe.name,
                "test_mode": is_test,
                "bytes": exe.stat().st_size,
                "sha256": sha256_file(exe),
                "iscc_tail": tail,
            }
        )
    return outputs


# ------------------------------------------------------- update metadata


def build_manifest(
    release: Path,
    version_config: Dict[str, Any],
    version: str,
    channel: str,
    update_url: str,
    installer: Path,
    sign: bool,
    notes: str,
) -> Dict[str, Any]:
    from service import update_manifest

    base = (update_url or "").rstrip("/")
    artifact_url = f"{base}/{installer.name}" if base else installer.name
    artifacts = {
        "windows-x64": {
            "url": artifact_url,
            "sha256": sha256_file(installer),
            "size": installer.stat().st_size,
            "filename": installer.name,
            "kind": "installer",
        }
    }

    document: Dict[str, Any] = {
        "manifest_schema": 1,
        "channel": channel,
        "version": version,
        "min_version": "0.0.0",
        "released_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "notes": notes,
        "artifacts": artifacts,
    }

    signed = False
    if sign and PRIVATE_KEY_FILE.is_file():
        document = update_manifest.build_signed_manifest(
            version=version,
            channel=channel,
            artifacts=artifacts,
            private_key_path=PRIVATE_KEY_FILE,
            min_version="0.0.0",
            released_at=document["released_at"],
            notes=notes,
        )
        signed = True
        log(f"manifest signed with {PRIVATE_KEY_FILE.name} (Ed25519)")
    elif sign:
        log(
            "WARNING: --sign requested but no private key at "
            f"{PRIVATE_KEY_FILE}; publishing an UNSIGNED manifest.\n"
            "         Existing installs will REJECT it (fail-closed). Run\n"
            "         'python -m packaging.signing.generate_keys' first."
        )

    manifest_path = release / "manifest.json"
    manifest_path.write_text(
        json.dumps(document, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return {
        "manifest": str(manifest_path),
        "signed": signed,
        "artifact_url": artifact_url,
        "sha256": artifacts["windows-x64"]["sha256"],
    }


def write_checksums(release: Path) -> Path:
    lines: List[str] = []
    for path in sorted(release.glob("*")):
        if path.is_file():
            lines.append(f"{sha256_file(path)}  {path.name}")
    target = release / "checksums.txt"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return target


# --------------------------------------------------------------------- main


def main(argv: Optional[Sequence[str]] = None) -> int:
    config = load_version_config()

    parser = argparse.ArgumentParser(description="Build the ProShield Windows release.")
    parser.add_argument("--version", default=config.get("version", "0.0.0"))
    parser.add_argument("--channel", default=config.get("channel", "testing"))
    parser.add_argument("--update-url", default=config.get("update_manifest_url", ""),
                        help="base URL that serves the release (used in manifest.json)")
    parser.add_argument("--notes", default="")
    parser.add_argument("--skip-frontend", action="store_true")
    parser.add_argument("--skip-runtime", action="store_true")
    parser.add_argument("--skip-service", action="store_true")
    parser.add_argument("--skip-desktop", action="store_true")
    parser.add_argument("--skip-installer", action="store_true")
    parser.add_argument("--with-testmode-installer", action="store_true",
                        help="also build the per-user, no-service test installer")
    parser.add_argument(
        "--publish-installer",
        choices=["primary", "testmode"],
        default="primary",
        help=(
            "which installer the signed update manifest describes. 'primary' "
            "(default) is the machine-wide installer; 'testmode' publishes the "
            "per-user installer so the testing channel can be exercised without "
            "elevation (requires --with-testmode-installer)."
        ),
    )
    parser.add_argument("--no-sign", action="store_true")
    parser.add_argument("--clean", action="store_true", help="remove the release dir first")
    args = parser.parse_args(argv)

    version = args.version
    started = time.time()
    release = RELEASE_ROOT / version
    stage = release / "_stage"
    work = release / "_pyinstaller"

    if os.name != "nt":
        raise SystemExit("ProShield releases are built on Windows.")

    if args.clean:
        rmtree(release)

    release.mkdir(parents=True, exist_ok=True)
    stage.mkdir(parents=True, exist_ok=True)
    work.mkdir(parents=True, exist_ok=True)

    git_commit = git_value(["rev-parse", "HEAD"])
    built_at = datetime.now(timezone.utc).isoformat(timespec="seconds")
    build_id = f"{version}+{datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S')}"

    build_info: Dict[str, Any] = {
        **config,
        "version": version,
        "channel": args.channel,
        "build_id": build_id,
        "git_commit": git_commit,
        "built_at": built_at,
        "tools": tool_versions(),
    }

    log("=" * 72)
    log(f"ProShield release build  version={version}  channel={args.channel}")
    log(f"release directory: {release}")
    log("=" * 72)

    report: Dict[str, Any] = {
        "version": version,
        "channel": args.channel,
        "build_id": build_id,
        "git_commit": git_commit,
        "built_at": built_at,
        "tools": build_info["tools"],
        "release_dir": str(release),
    }

    report["frontend"] = stage_frontend(args.skip_frontend)
    report["sources"] = stage_sources(stage, config, build_info)
    report["runtime"] = stage_runtime(stage, args.skip_runtime)

    if args.skip_service:
        log("service freeze skipped")
    else:
        report["service"] = freeze_service(stage, work)

    if args.skip_desktop:
        log("desktop freeze skipped")
    else:
        report["desktop"] = freeze_desktop(stage, work)

    # Requirement 11: the payload must contain no caches, no compiled artefacts,
    # no debug dumps, no development secrets and no legacy frontend files.
    report["pruned"] = prune_stage(stage)
    log(f"payload pruned: {report['pruned']}")
    report["frozen_freshness"] = verify_frozen_freshness(stage)
    log("frozen artefact freshness check passed (binaries are not stale)")
    report["payload_audit"] = audit_stage(stage)
    log("payload audit passed (no caches, no legacy frontend, no signing key)")

    installers: List[Dict[str, Any]] = []
    if args.skip_installer:
        log("installer build skipped")
    else:
        installers = build_installer(
            release, stage, version, args.update_url, args.with_testmode_installer
        )
    report["installers"] = installers

    # ---- top-level deliverables (requirement 13) ----------------------
    service_exe = stage / "service" / "ProShieldService.exe"
    desktop_exe = stage / "desktop" / "ProShield.exe"
    if service_exe.is_file():
        shutil.copy2(service_exe, release / "ProShieldService.exe")
    if desktop_exe.is_file():
        shutil.copy2(desktop_exe, release / "ProShield.exe")

    primary_installer: Optional[Path] = None
    testmode_installer: Optional[Path] = None
    for item in installers:
        if item.get("test_mode"):
            testmode_installer = Path(item["installer"])
        else:
            primary_installer = Path(item["installer"])

    # The canonical "install me" file is always the machine-wide installer.
    if primary_installer is not None:
        shutil.copy2(primary_installer, release / "ProShieldSetup.exe")

    # Which installer the *update manifest* describes.  A production channel
    # publishes the machine-wide installer (the service runs as LocalSystem and
    # applies it without a prompt).  The testing channel may publish the
    # per-user test-mode installer so the identical detect -> verify -> apply ->
    # restart -> health-check path can be exercised without elevation.
    published_installer = primary_installer
    if args.publish_installer == "testmode":
        if testmode_installer is None:
            raise SystemExit(
                "--publish-installer testmode needs --with-testmode-installer"
            )
        published_installer = testmode_installer
    if published_installer is None:
        published_installer = primary_installer or testmode_installer
    report["published_installer"] = (
        published_installer.name if published_installer else None
    )

    if published_installer is not None:
        report["manifest_info"] = build_manifest(
            release,
            config,
            version,
            args.channel,
            args.update_url,
            published_installer,
            sign=not args.no_sign,
            notes=args.notes or f"ProShield {version} ({args.channel} channel)",
        )
    else:
        log("no installer produced: manifest.json not generated")

    report["checksums"] = str(write_checksums(release))
    report["duration_seconds"] = round(time.time() - started, 1)

    (release / "build-report.json").write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    log("")
    log("=" * 72)
    log("RELEASE ARTEFACTS")
    log("=" * 72)
    for path in sorted(release.glob("*")):
        if path.is_file():
            size = path.stat().st_size
            log(f"  {path.name:<34} {size:>12,} bytes  sha256={sha256_file(path)[:16]}...")
    log("")
    log(f"build completed in {report['duration_seconds']}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))